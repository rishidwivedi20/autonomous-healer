def to_html(rep: dict) -> str:
    e = html.escape
    sc, an = rep["score"], rep["analysis"]
    how = f"LLM agent ({e(str(an['model']))})" if an["by"] == "llm" else "deterministic rules"
    h = [f"<!doctype html><html lang=en><meta charset=utf-8><meta name=viewport content='width=device-width,initial-scale=1'>"
         f"<title>Resilience findings</title><style>{_CSS}</style><main><h1>Resilience findings report</h1>"
         f"<p class=mut>Generated {e(rep['generated_at'])} for {e(rep['application'])}. Analysis by {how}"
         + (f" (rule-based fallback because: {e(an['fallback_reason'])})" if an["fallback_reason"] else "") + ".</p>"]
    h.append("<h2>Resilience score</h2>")
    if sc["score"] is None:
        h.append("<p>No score: no experiment had a measurable result.</p>")
    else:
        h.append(f"<div class=card><span class='big {e(sc['band'])}'>{sc['score']:.1f}</span> / 100 "
                 f"<b class={e(sc['band'])}>{e(sc['band'])}</b><p class=mut>Latest run of each of {sc['n_experiments']} distinct "
                 f"experiments ({sc['n_runs']} runs stored).</p><table><tr><th>Component<th>Weight<th>Score</tr>"
                 + "".join(f"<tr><td>{e(k.replace('_', ' '))}<td>{sc['weights'][k]}<td>{_num(v, '', 1)}</tr>" for k, v in sc["by_component"].items())
                 + f"</table><p class=mut>Formula: {e(sc['formula'])}.</p></div>")
    h.append(f"<h2>Summary</h2><p>{e(an['summary'])}</p><h2>Ranked weaknesses</h2>")
    for w in rep["weaknesses"]:
        h.append(f"<div class=card><h3>{w['n']}. <span class='sev {e(w['severity'])}'>{e(w['severity'].upper())}</span> {e(w['title'])}</h3>"
                 f"<p class=mut>Affected: {e(', '.join(w['services']))}</p><p>{e(w['description'])}</p><ul>"
                 + "".join(f"<li>{e(x['claim'])} <code>{e(x['experiment_id'])}</code>" for x in w["evidence"]) + "</ul></div>")
    h.append("<h2>Recommended fixes</h2>")
    for n, f in enumerate(rep["fixes"], 1):
        h.append(f"<div class=card><h3>{n}. {e(f['title'])}</h3><p class=mut>Addresses: {e('; '.join(f['addresses']) or '-')}</p>"
                 f"<p>Why: {e(f['rationale'])}</p><pre>{e(f['change'].rstrip())}</pre>")
        if f["verification"]:
            h.append("<p>Verify by re-running:</p><ul>" + "".join(
                f"<li><code>{e(v['command'])}</code>: was {_num(v['score_before'], '', 1)}; {e(v['pass_if'])}" for v in f["verification"]) + "</ul>")
        h.append("</div>")
    h.append("<h2>Experiments</h2><table><tr><th>Experiment<th>Target<th>Fault<th>Score<th>Worst journey errors<th>Recovery<th>Aborted<th>Restarts</tr>")
    for r in rep["experiments"]:
        rec = _num(r["recovery_s"], " s") if r["recovered"] else "not recovered"
        rs = ", ".join(f"{k} x{v}" for k, v in r["restarts"].items() if v) or "-"
        worst = f"{_pct(r['worst_error_rate'])} ({r['worst_journey']})" if r["worst_journey"] else "n/a"
        h.append(f"<tr><td><code>{e(r['id'])}</code><td>{e(r['target'])}<td>{e(r['fault'])}<td class={e(r['band'] or '')}>{_num(r['score'], '', 1)}"
                 f"<td>{e(worst)}<td>{e(rec)}<td>{e('yes: ' + str(r['abort_reason'])) if r['aborted'] else 'no'}<td>{e(rs)}</tr>")
    h.append("</table><h2>Per-experiment detail</h2>")
    for r in rep["experiments"]:
        h.append(f"<h3>{e(r['id'])}</h3><p class=mut>{e(r['fault'])} on {e(r['target'])} for {r['duration_s']} s</p><ul>"
                 + "".join(f"<li>{e(c['name'].replace('_', ' '))} ({c['weight']}): {_num(c['score'], '', 2)}. {e(c['basis'])}" for c in r["components"])
                 + (f"<li>root cause: {e(r['analysis']['root_cause'])}" if r["analysis"] else "")
                 + "".join(f"<li>missing: {e(m)}" for m in r["missing_signals"])
                 + "".join(f"<li>rollback error: {e(m)}" for m in r["rollback_errors"]) + "</ul>")
    h.append("<h2>Limitations</h2><ul>" + "".join(f"<li>{e(x)}" for x in rep["limitations"]) + "</ul></main>")
    return "".join(h)


def write(out_dir: Path | str, rep: dict) -> dict[str, Path]:
    import json
    d = Path(out_dir)
    paths = {"json": d / "findings.json", "md": d / "findings.md", "html": d / "findings.html"}
    paths["json"].write_text(json.dumps(rep, indent=2), encoding="utf-8")
    paths["md"].write_text(to_markdown(rep), encoding="utf-8")
    paths["html"].write_text(to_html(rep), encoding="utf-8")
    return paths

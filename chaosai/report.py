"""The findings report: results/findings.{json,md,html}, built only from stored results.

Nothing here is generated by a model. The experiment table, the score and the verification steps are computed
from the stored measurements; the weaknesses and fixes are whatever the analyzer produced (LLM or rules), and
the report says which. Every number in an evidence line was already validated against the stored data.
"""
from __future__ import annotations

import html
import time
from pathlib import Path
from typing import Optional

from .analysis import Analysis
from .models import ExperimentResult, Graph
from .scoring import OverallScore, WEIGHTS, overall, score_experiment

MAX_VERIFY = 2          # re-run the worst-scoring experiments a fix was argued from; a 99/100 run cannot show improvement

LIMITATIONS = [
    "One laptop, one replica of every service: results describe this sandbox, not production.",
    "Each experiment is a single run; repeat runs of the same fault vary (error rates and stall lengths moved between runs). Only the latest run of each distinct experiment counts toward the score.",
    "User impact is measured with HTTP probes (5 requests/s per journey); the pipeline is measured with the redis queue length and the Postgres row count. Anything not measured is listed as missing, not guessed.",
    "Causes marked as inference are consistent with the measurements but were not observed directly.",
    "Vote loss is not reconciled end to end yet: accepted votes are not compared with stored votes in every run.",
]


# ------------------------------------------------------------------ building
def _worst(r: ExperimentResult) -> tuple[Optional[str], Optional[float]]:
    pairs = [(j, s.error_rate) for j, s in r.during_by_journey.items() if s.n and s.error_rate is not None]
    if not pairs and r.during.n and r.during.error_rate is not None:      # older results have no per-journey split
        pairs = [("all", r.during.error_rate)]
    return max(pairs, key=lambda p: p[1]) if pairs else (None, None)


def _row(r: ExperimentResult, sc, restarts: dict) -> dict:
    j, err = _worst(r)
    return {
        "id": r.experiment.id, "target": r.experiment.target, "fault": r.experiment.fault, "params": r.experiment.params,
        "started_at": r.started_at, "duration_s": r.experiment.duration_s, "hypothesis": r.experiment.hypothesis, "score": sc.score, "band": sc.band,
        "worst_journey": j, "worst_error_rate": err,
        "p95_ms": {k: [r.baseline_by_journey[k].p95_ms if k in r.baseline_by_journey else None, v.p95_ms]
                   for k, v in r.during_by_journey.items()},
        "recovered": r.recovered, "recovery_s": r.recovery_s, "recovery_probe_s": r.recovery_probe_s,
        "recovery_pipeline_s": r.recovery_pipeline_s, "pipeline_assessed": r.pipeline_assessed,
        "aborted": r.aborted, "abort_reason": r.abort_reason, "restarts": restarts,
        "rollback_errors": r.rollback_errors, "missing_signals": r.missing_signals, "notes": r.notes,
        "components": [c.model_dump() for c in sc.components],
    }


def _command(target: str, fault: str, params: dict) -> str:
    return f"chaos run {target} {fault}" + "".join(f" -p {k}={v}" for k, v in sorted(params.items()))


def _verification(evidence_ids: list[str], rows: dict[str, dict]) -> list[dict]:
    """Re-run the worst-scoring experiments the fix was argued from; the fix helped only if their score goes up."""
    best: dict[tuple, dict] = {}
    for i in evidence_ids:                                   # one entry per distinct experiment, its most recent cited run
        row = rows.get(i)
        key = (row["target"], row["fault"], str(sorted(row["params"].items()))) if row else None
        if row and (key not in best or row["started_at"] >= best[key]["started_at"]):
            best[key] = row
    worst_first = sorted(best.values(), key=lambda r: (r["score"] is None, r["score"] if r["score"] is not None else 0))
    return [{"command": _command(r["target"], r["fault"], r["params"]), "experiment_id": r["id"], "score_before": r["score"],
             "pass_if": "its resilience score is higher than score_before, with no new aborts or rollback errors"}
            for r in worst_first[:MAX_VERIFY]]


def build(ev, analysis: Analysis, graph: Optional[Graph] = None, scope: Optional[list[str]] = None,
          now: Optional[float] = None) -> dict:
    results = ev.results()
    ids = [i for i in (scope or ev.ids()) if i in results]
    scores = [score_experiment(results[i], graph, ev.restarts_of(i)) for i in ids]
    total: OverallScore = overall(scores)
    rows = {s.experiment_id: _row(results[s.experiment_id], s, ev.restarts_of(s.experiment_id)) for s in scores}
    by_exp = {e.experiment_id: e for e in analysis.experiments}
    for i, row in rows.items():
        a = by_exp.get(i)
        row["analysis"] = ({"hypothesis_held": a.hypothesis_held, "root_cause": a.root_cause, "blast_radius": a.blast_radius,
                            "evidence": [e.model_dump() for e in a.evidence]} if a else None)
    weaknesses = [{**w.model_dump(), "n": n} for n, w in enumerate(analysis.weaknesses, 1)]
    fixes = []
    for f in analysis.fixes:
        cited = [e.experiment_id for e in f.evidence] + [e.experiment_id for w in analysis.weaknesses if w.title in f.addresses
                                                         for e in w.evidence]
        fixes.append({**f.model_dump(), "verification": _verification(cited, rows)})
    return {
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(now if now is not None else time.time())),
        "application": "Docker example-voting-app (vote -> redis -> worker -> postgres -> result)",
        "analysis": {"by": analysis.generated_by, "model": analysis.model, "fallback_reason": analysis.fallback_reason,
                     "summary": analysis.summary, "notes": analysis.notes},
        "score": {**total.model_dump(exclude={"experiments"}), "weights": WEIGHTS},
        "experiments": [rows[i] for i in ids], "weaknesses": weaknesses, "fixes": fixes,
        "dependency_graph": ({"critical_path": graph.critical_path,
                              "depends_on": {n: s.depends_on for n, s in graph.services.items()}} if graph else None),
        "limitations": LIMITATIONS,
    }


# ------------------------------------------------------------------ rendering
def _pct(x: Optional[float]) -> str:
    return "n/a" if x is None else f"{x:.0%}"


def _num(x: Optional[float], unit: str = "", nd: int = 0) -> str:
    return "n/a" if x is None else f"{x:.{nd}f}{unit}"


def _cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def to_markdown(rep: dict) -> str:
    sc, an = rep["score"], rep["analysis"]
    L = ["# Resilience findings report", "",
         f"_Generated {rep['generated_at']} for {rep['application']}._", ""]
    how = f"LLM agent ({an['model']})" if an["by"] == "llm" else "deterministic rules"
    L += [f"**Analysis by:** {how}" + (f" (rule-based fallback because: {an['fallback_reason']})" if an["fallback_reason"] else ""), "",
          "## Resilience score", ""]
    if sc["score"] is None:
        L += ["No score: no experiment had a measurable result.", ""]
    else:
        L += [f"### {sc['score']:.1f} / 100 ({sc['band']})", "",
              f"Counted: the latest run of each of {sc['n_experiments']} distinct experiments ({sc['n_runs']} runs stored).", "",
              "| Component | Weight | Score |", "|---|---|---|"]
        L += [f"| {k.replace('_', ' ')} | {sc['weights'][k]} | {_num(v, '', 1)} |" for k, v in sc["by_component"].items()]
        L += ["", f"Formula: {sc['formula']}.", ""]
    L += ["## Summary", "", an["summary"], "", "## Ranked weaknesses", ""]
    for w in rep["weaknesses"]:
        L += [f"### {w['n']}. [{w['severity'].upper()}] {w['title']}", "", f"Affected: {', '.join(w['services'])}", "", w["description"], "",
              "Evidence:"] + [f"- {e['claim']} (`{e['experiment_id']}`)" for e in w["evidence"]] + [""]
    L += ["## Recommended fixes", ""]
    for n, f in enumerate(rep["fixes"], 1):
        L += [f"### {n}. {f['title']}", "", f"Addresses: {'; '.join(f['addresses']) or '-'}", "", f"Why: {f['rationale']}", "",
              "```", f["change"].rstrip(), "```", ""]
        if f["verification"]:
            L.append("Verify by re-running:")
            L += [f"- `{v['command']}`: was {_num(v['score_before'], '', 1)}; {v['pass_if']}" for v in f["verification"]]
            L.append("")
    L += ["## Experiments", "", "| Experiment | Target | Fault | Score | Worst journey errors | Recovery | Aborted | Restarts |",
          "|---|---|---|---|---|---|---|---|"]
    for r in rep["experiments"]:
        rec = _num(r["recovery_s"], " s") if r["recovered"] else "not recovered"
        rs = ", ".join(f"{k} x{v}" for k, v in r["restarts"].items() if v) or "-"
        worst = f"{_pct(r['worst_error_rate'])} ({r['worst_journey']})" if r["worst_journey"] else "n/a"
        L.append(f"| `{_cell(r['id'])}` | {r['target']} | {r['fault']} | {_num(r['score'], '', 1)} | {worst} | {rec} | "
                 f"{'yes: ' + _cell(r['abort_reason']) if r['aborted'] else 'no'} | {_cell(rs)} |")
    L += ["", "## Per-experiment detail", ""]
    for r in rep["experiments"]:
        L += [f"### {r['id']}", "", f"{r['fault']} on {r['target']} for {r['duration_s']} s. Score "
              f"{_num(r['score'], '', 1)} ({r['band'] or 'n/a'}).", ""]
        L += [f"- {c['name'].replace('_', ' ')} ({c['weight']}): {_num(c['score'], '', 2)}. {c['basis']}" for c in r["components"]]
        if r["recovery_probe_s"] is not None or r["recovery_pipeline_s"] is not None:
            L.append(f"- recovery: users back after {_num(r['recovery_probe_s'], ' s')}, pipeline back after {_num(r['recovery_pipeline_s'], ' s')}")
        a = r["analysis"]
        if a:
            L.append(f"- root cause ({'hypothesis held' if a['hypothesis_held'] else 'hypothesis not held' if a['hypothesis_held'] is False else 'no hypothesis stored'}): {a['root_cause']}")
        L += [f"- missing: {m}" for m in r["missing_signals"]] + [f"- rollback error: {m}" for m in r["rollback_errors"]] + [""]
    L += ["## Limitations", ""] + [f"- {x}" for x in rep["limitations"]] + [""]
    return "\n".join(L)


